DIFF = """diff --git a/src/A.cs b/src/A.cs
index 1111111..2222222 100644
--- a/src/A.cs
+++ b/src/A.cs
@@ -1,3 +1,4 @@ class A
 line1
-old
+new
+added
 line3
@@ -10,2 +11,2 @@ void M()
-x
+y
 z
diff --git a/tests/T/Resources/Case(a, b)/Out.g.cs b/tests/T/Resources/Case(a, b)/Out.g.cs
new file mode 100644
index 0000000..3333333
--- /dev/null
+++ b/tests/T/Resources/Case(a, b)/Out.g.cs\t
@@ -0,0 +1 @@
+// <auto-generated/>
"""


def test_parse_diff_hunks_and_tab_terminated_paths():
    files, hunks = parse_diff(DIFF)
    assert [f.path for f in files] == ["src/A.cs", "tests/T/Resources/Case(a, b)/Out.g.cs"]
    a, gen = files
    assert (a.status, a.additions, a.deletions, a.kind) == ("modified", 3, 2, "source")
    assert (gen.status, gen.kind) == ("added", "generated")
    assert [h.id for h in hunks] == ["src/A.cs#1", "src/A.cs#2", "tests/T/Resources/Case(a, b)/Out.g.cs#1"]
    assert hunks[0].header == "class A"
    assert (hunks[1].old_start, hunks[1].old_lines, hunks[1].new_start, hunks[1].new_lines) == (10, 2, 11, 2)
    assert (hunks[2].old_lines, hunks[2].new_lines) == (0, 1)


